"""
fill_missing_translations.py  -  one-time helper, run from the project root:

    python fill_missing_translations.py

What it does
  1. Reads static/js/translations.js and finds, for every language in the picker,
     the UI strings that are missing or still in English.
  2. Translates ONLY those strings (Gemini translate key first, Groq as fallback,
     slowly, in small chunks), and keeps the results in translations_generated.json.
  3. Writes static/js/translations-generated.js, which the app loads after
     translations-extra.js.

It is safe to stop and re-run: finished strings are kept, only the rest is retried.
Hindi and Bengali are hand-written in translations-extra.js, so they are skipped.
Have a native speaker read a sample of each language before the demo.
"""
import ast
import json
import os
import re
import sys
import time

from shared import LANG_NAMES, _translate_terms_chunk_full

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, "static", "js", "translations.js")
GEN_JSON = os.path.join(ROOT, "translations_generated.json")
OUT_JS = os.path.join(ROOT, "static", "js", "translations-generated.js")

PICKER = ["hi", "pa", "mr", "te", "ta", "bn", "gu", "kn", "ml", "or", "as", "ur"]
SKIP = {"hi", "bn"}          # already hand-written in translations-extra.js
CHUNK = 40                   # terms per request
PAUSE_BETWEEN_CHUNKS = 4     # seconds, keeps you under per-minute limits
PAUSE_BETWEEN_PASSES = 30    # seconds
MAX_PASSES = 3

DOMAIN_NOTE = (
    "These are short interface labels, headings and sentences for a farming app used by "
    "Indian farmers on phones. Keep them short and natural. Keep emojis, symbols (⚠ ✓ % •), "
    "numbers, file types (JPG, PNG, WEBP), units and the app name SmartAgro unchanged."
)

LANG_START = re.compile(r"^    ([a-z]+): \{\s*$")
ENTRY = re.compile(
    r"""^\s+([A-Za-z0-9_]+):\s*('(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*")\s*,?\s*(?://.*)?$"""
)


def parse_translations(path):
    data, cur = {}, None
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\n")
            m = LANG_START.match(line)
            if m:
                cur = m.group(1)
                data.setdefault(cur, {})
                continue
            if cur is None:
                continue
            if line.startswith("    }"):
                cur = None
                continue
            m = ENTRY.match(line)
            if m:
                try:
                    data[cur][m.group(1)] = ast.literal_eval(m.group(2))
                except Exception:
                    pass
    return data


def has_letters(text):
    return bool(re.search(r"[A-Za-z]", text or ""))


def write_js(gen):
    body = json.dumps(gen, ensure_ascii=False, indent=2)
    js = (
        "/* AUTO-GENERATED by fill_missing_translations.py - do not edit by hand. */\n"
        "(function () {\n"
        "    var EXTRA = " + body.replace("\n", "\n    ") + ";\n"
        "    if (window.mergeTranslations) window.mergeTranslations(EXTRA);\n"
        "})();\n"
    )
    with open(OUT_JS, "w", encoding="utf-8") as f:
        f.write(js)


def main():
    if not os.path.exists(SRC):
        sys.exit(f"Cannot find {SRC}. Run this from the project root.")

    T = parse_translations(SRC)
    EN = {k: v.replace("23 languages", "13 languages") for k, v in T.get("en", {}).items()}
    if not EN:
        sys.exit("Could not read the English block from translations.js")

    gen = {}
    if os.path.exists(GEN_JSON):
        with open(GEN_JSON, encoding="utf-8") as f:
            gen = json.load(f)

    langs = [l for l in PICKER if l not in SKIP]
    if len(sys.argv) > 1:
        langs = [l for l in sys.argv[1:] if l in PICKER]

    for lang in langs:
        have = T.get(lang, {})
        done_keys = gen.setdefault(lang, {})
        need = {}
        for key, en_val in EN.items():
            cur = have.get(key)
            if key in done_keys or not has_letters(en_val):
                continue
            if cur is None or cur == "" or cur == en_val:
                need[key] = en_val
        if not need:
            print(f"[{lang}] nothing missing")
            continue

        terms = list(dict.fromkeys(need.values()))
        print(f"[{lang}] {len(need)} keys ({len(terms)} unique strings) to translate")
        done = {}
        lang_name = LANG_NAMES.get(lang, lang)

        for attempt in range(1, MAX_PASSES + 1):
            todo = [t for t in terms if t not in done]
            if not todo:
                break
            for i in range(0, len(todo), CHUNK):
                chunk = todo[i:i + CHUNK]
                trans, returned = _translate_terms_chunk_full(chunk, lang_name, DOMAIN_NOTE, lang)
                for t in returned:
                    val = trans[t].strip() if t.strip() == t else trans[t]
                    if val and val != t:
                        done[t] = val
                print(f"   pass {attempt}: {len(done)}/{len(terms)} done")
                time.sleep(PAUSE_BETWEEN_CHUNKS)
            if any(t not in done for t in terms) and attempt < MAX_PASSES:
                print(f"   waiting {PAUSE_BETWEEN_PASSES}s before retrying the rest...")
                time.sleep(PAUSE_BETWEEN_PASSES)

        for key, en_val in need.items():
            if en_val in done:
                val = done[en_val]
                if en_val.endswith(" ") and not val.endswith(" "):
                    val += " "      # keep the trailing space the page code relies on
                done_keys[key] = val

        left = sum(1 for t in terms if t not in done)
        print(f"[{lang}] finished, {left} strings still untranslated (they stay English)")

        with open(GEN_JSON, "w", encoding="utf-8") as f:
            json.dump(gen, f, ensure_ascii=False, indent=1)
        write_js(gen)

    write_js(gen)
    print("Done. Wrote", OUT_JS)


if __name__ == "__main__":
    main()